def get_theme(name: str) -> dict:
    """Devuelve la configuración del tema solicitado o el tema oscuro por defecto."""
    return THEMES.get(name, THEMES["oscuro"])


def configure_ttk_styles(root, theme: dict) -> ttk.Style:
    """Aplica estilos ttk coherentes y accesibles para el tema activo."""
    style = ttk.Style(root)
    try:
        style.theme_use("clam")
    except Exception:
        pass

    style.configure("App.TFrame", background=theme["app_bg"])
    style.configure("Toolbar.TFrame", background=theme["toolbar_bg"])
    style.configure("Panel.TFrame", background=theme["panel_bg"])
    style.configure("Status.TFrame", background=theme["status_bg"])

    style.configure(
        "Toolbar.TLabel",
        background=theme["toolbar_bg"],
        foreground=theme["header_fg"],
    )
    style.configure(
        "PanelHeader.TLabel",
        background=theme["panel_bg"],
        foreground=theme["muted_fg"],
        font=("Segoe UI", 9, "bold"),
    )
    style.configure(
        "Status.TLabel",
        background=theme["status_bg"],
        foreground=theme["status_fg"],
        padding=(8, 3),
    )

    # Botones semánticos con foco visible
    style.configure(
        "Run.TButton",
        background=theme["btn_run_bg"],
        foreground=theme["btn_run_fg"],
        borderwidth=1,
        bordercolor=theme["btn_run_bg"],
        focuscolor=theme["focus_ring"],
        padding=(12, 5),
        font=("Segoe UI", 10, "bold"),
    )
    style.map(
        "Run.TButton",
        background=[
            ("disabled", theme["btn_disabled_bg"]),
            ("active", theme["btn_run_hover"]),
            ("pressed", theme["btn_run_hover"]),
        ],
        foreground=[("disabled", theme["btn_disabled_fg"])],
        bordercolor=[("focus", theme["focus_ring"])],
    )

    style.configure(
        "Stop.TButton",
        background=theme["btn_stop_bg"],
        foreground=theme["btn_stop_fg"],
        borderwidth=1,
        bordercolor=theme["btn_stop_bg"],
        focuscolor=theme["focus_ring"],
        padding=(10, 5),
        font=("Segoe UI", 10, "bold"),
    )
    style.map(
        "Stop.TButton",
        background=[
            ("disabled", theme["btn_disabled_bg"]),
            ("active", theme["btn_stop_hover"]),
            ("pressed", theme["btn_stop_hover"]),
        ],
        foreground=[("disabled", theme["btn_disabled_fg"])],
        bordercolor=[("focus", theme["focus_ring"])],
    )

    style.configure(
        "Neutral.TButton",
        background=theme["btn_neutral_bg"],
        foreground=theme["btn_neutral_fg"],
        borderwidth=1,
        bordercolor=theme["border"],
        focuscolor=theme["focus_ring"],
        padding=(9, 4),
        font=("Segoe UI", 9),
    )
    style.map(
        "Neutral.TButton",
        background=[
            ("disabled", theme["btn_disabled_bg"]),
            ("active", theme["btn_neutral_hover"]),
            ("pressed", theme["btn_neutral_hover"]),
        ],
        foreground=[("disabled", theme["btn_disabled_fg"])],
        bordercolor=[("focus", theme["focus_ring"])],
    )

    style.configure(
        "Toolbar.TCheckbutton",
        background=theme["toolbar_bg"],
        foreground=theme["header_fg"],
        indicatorcolor=theme["panel_bg"],
        focuscolor=theme["focus_ring"],
        font=("Segoe UI", 9),
    )
    style.map(
        "Toolbar.TCheckbutton",
        background=[("active", theme["toolbar_bg"])],
        indicatorcolor=[("selected", theme["btn_run_bg"])],
    )

    style.configure(
        "App.TCombobox",
        fieldbackground=theme["panel_bg"],
        background=theme["btn_neutral_bg"],
        foreground=theme["editor_fg"],
        arrowcolor=theme["editor_fg"],
        bordercolor=theme["border"],
        lightcolor=theme["border"],
        darkcolor=theme["border"],
    )
    style.map(
        "App.TCombobox",
        fieldbackground=[("readonly", theme["panel_bg"])],
        foreground=[("readonly", theme["editor_fg"])],
        bordercolor=[("focus", theme["focus_ring"])],
    )

    style.configure(
        "App.TEntry",
        fieldbackground=theme["panel_bg"],
        foreground=theme["editor_fg"],
        insertcolor=theme["cursor"],
        bordercolor=theme["border"],
        lightcolor=theme["border"],
        darkcolor=theme["border"],
    )
    style.map("App.TEntry", bordercolor=[("focus", theme["focus_ring"])])

    # Notebook (pestañas de archivos)
    style.configure(
        "Editor.TNotebook",
        background=theme["panel_bg"],
        borderwidth=0,
        tabmargins=(2, 2, 2, 0),
    )
    style.configure(
        "Editor.TNotebook.Tab",
        background=theme["tab_bg"],
        foreground=theme["tab_fg"],
        padding=(12, 5),
        borderwidth=1,
        focuscolor=theme["focus_ring"],
        font=("Segoe UI", 9),
    )
    style.map(
        "Editor.TNotebook.Tab",
        background=[("selected", theme["tab_selected_bg"])],
        foreground=[("selected", theme["tab_selected_fg"])],
        font=[("selected", ("Segoe UI", 9, "bold"))],
    )

    style.configure(
        "Debug.TButton",
        background=theme["btn_debug_bg"],
        foreground=theme["btn_debug_fg"],
        borderwidth=1,
        bordercolor=theme["btn_debug_bg"],
        focuscolor=theme["focus_ring"],
        padding=(10, 5),
        font=("Segoe UI", 10, "bold"),
    )
    style.map(
        "Debug.TButton",
        background=[
            ("disabled", theme["btn_disabled_bg"]),
            ("active", theme["btn_debug_hover"]),
            ("pressed", theme["btn_debug_hover"]),
        ],
        foreground=[("disabled", theme["btn_disabled_fg"])],
        bordercolor=[("focus", theme["focus_ring"])],
    )

    style.configure(
        "App.Treeview",
        background=theme["panel_bg"],
        fieldbackground=theme["panel_bg"],
        foreground=theme["editor_fg"],
        bordercolor=theme["border"],
        rowheight=24,
        font=("Consolas", 9),
    )
    style.map(
        "App.Treeview",
        background=[("selected", theme["selection_bg"])],
        foreground=[("selected", theme["selection_fg"])],
    )
    style.configure(
        "App.Treeview.Heading",
        background=theme["toolbar_bg"],
        foreground=theme["header_fg"],
        bordercolor=theme["border"],
        font=("Segoe UI", 9, "bold"),
    )
    style.map("App.Treeview.Heading", background=[("active", theme["btn_neutral_hover"])])

    # Scrollbars estilizados
    for orient in ("Vertical", "Horizontal"):
        style.configure(
            f"App.{orient}.TScrollbar",
            troughcolor=theme["scrollbar_trough"],
            background=theme["scrollbar_thumb"],
            bordercolor=theme["scrollbar_trough"],
            arrowcolor=theme["muted_fg"],
            gripcount=0,
            relief="flat",
        )
        style.map(
            f"App.{orient}.TScrollbar",
            background=[
                ("active", theme["scrollbar_active"]),
                ("pressed", theme["focus_ring"]),
            ],
        )

    return style
